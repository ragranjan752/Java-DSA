package Strings;

public class SubStringOfString {
    static void main(String[] args) {
        String s = "raushandeepakranjan";
        System.out.println(s.substring(0, 7)); //raushan
        System.out.println(s.substring(7, 13)); // deepak
        System.out.println(s.substring(13, 19)); //ranjan
    }
}
