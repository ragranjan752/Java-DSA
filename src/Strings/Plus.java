package Strings;

public class Plus {
    static void main(String[] args) {
        String s = "rag";
        s += " is also known as raushan ";
        s += '\n';
        s += 10;
        s += 'a';
        System.out.println(s);
        System.out.println("Rag" + 10 + 20);
        System.out.println("Rag" + (10 + 20));
        System.out.println(10 + 20 + " Rag");
        System.out.println(10 + "Rag" + 20);
        System.out.println('A' + 2 + "Rag");
        System.out.println('A'+"isha");
    }
}
